# --- Load best params from JSON files ---
OPTUNA_PARAMS = {}

# optuna_results/{dim}d_params.json (generated by optimize_umap.py)
for dim in [2, 3, 4, 5, 6, 7, 8]:
    path = f"optuna_results/{dim}d_params.json"
    if os.path.exists(path):
        with open(path) as f:
            data = json.load(f)
            OPTUNA_PARAMS[dim] = data["best_params"]


# --- Cached functions ---
@st.cache_data
def load_embeddings(file):
    return np.load(file).astype("float32")


@st.cache_data
def load_metadata(file):
    return pd.read_csv(file)


@st.cache_data
def run_umap(
    X,
    n_neighbors,
    min_dist,
    n_components,
    metric,
    seed,
    method,
    dens_lambda=None,
    dens_frac=None,
    dens_var_shift=None,
):
    reducer_kwargs = dict(
        n_neighbors=n_neighbors,
        min_dist=min_dist,
        n_components=n_components,
        metric=metric,
        random_state=seed,
    )

    if method == "densMAP":
        reducer_kwargs.update(
            densmap=True,
            dens_lambda=dens_lambda,
            dens_frac=dens_frac,
            dens_var_shift=dens_var_shift,
        )

    reducer = umap.UMAP(**reducer_kwargs)
    return reducer.fit_transform(X)


